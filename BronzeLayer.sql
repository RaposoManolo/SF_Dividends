USE DATABASE DIVIDENDS_DEV;

CREATE OR REPLACE FILE FORMAT DV_CSV
    TYPE = 'CSV'
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    DATE_FORMAT = 'DD/MM/YYYY'
    NULL_IF = ('-', '');

Create or Replace Stage STG_Dividends
File_Format = DV_CSV    

CREATE OR REPLACE TABLE Bronze.DIVIDEND (
    RECORD_DATE         DATE,          -- e.g., '30/10/2026' (Format DD/MM/YYYY)
    DESCRIPTION         VARCHAR(255),  -- e.g., 'DIVIDEND 13 TD SYNNEX CORPORATION...'
    DIVIDEND_REFERENCE  VARCHAR(50),   -- e.g., '9989624 / 10'
    SETTLEMENT_DATE     DATE,          -- Can handle NULL or missing '-' entries
    RECEIPT_GBP         NUMBER(12, 2), -- e.g., 4.64
    PAYMENT_GBP         NUMBER(12, 2), -- e.g., 0.00
    BALANCE_GBP         VARCHAR(50)  -- e.g., 12509.78
);


SELECT * from STG_Dividends


COPY INTO BRONZE_DIVIDENDS
FROM @STG_DIVIDENDS
FILE_FORMAT = (
    FORMAT_NAME = DV_CSV
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE
);




MERGE INTO bronze.dividends AS target
USING (
    SELECT 
        TO_DATE($1, 'DD/MM/YYYY') AS RECORD_DATE,
        $2::VARCHAR(255)          AS DESCRIPTION,
        $3::VARCHAR(50)           AS DIVIDEND_REFERENCE,
        TO_DATE($4, 'DD/MM/YYYY') AS SETTLEMENT_DATE,
        $5::NUMBER(12, 2)         AS RECEIPT_GBP,
        $6::NUMBER(12, 2)         AS PAYMENT_GBP,
        $7::VARCHAR(50)           AS BALANCE_GBP
    FROM @STG_Dividends (FILE_FORMAT => 'DV_CSV')
) AS source
ON target.DIVIDEND_REFERENCE = source.DIVIDEND_REFERENCE
   AND target.RECORD_DATE = source.RECORD_DATE
WHEN NOT MATCHED THEN
    INSERT (RECORD_DATE, DESCRIPTION, DIVIDEND_REFERENCE, SETTLEMENT_DATE, RECEIPT_GBP, PAYMENT_GBP, BALANCE_GBP)
    VALUES (source.RECORD_DATE, source.DESCRIPTION, source.DIVIDEND_REFERENCE, source.SETTLEMENT_DATE, source.RECEIPT_GBP, source.PAYMENT_GBP, source.BALANCE_GBP);



Select * from bronze.dividends

Drop tables DIVIDENDS_DEV.BRONZE.DIVIDEND